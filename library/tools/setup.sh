#!/usr/bin/env bash
# setup.sh <project_dir> [brand]
# New project for a brand: engine + Studio Library + the brand's profile, characters and backgrounds.
# brand = a folder in brands/ (default: buzztorm). Example: setup.sh ~/studio/buzztorm/daily-posting buzztorm
set -e
KIT="$(cd "$(dirname "$0")/.." && pwd)"            # library/
ROOT="$(cd "$KIT/.." && pwd)"                       # repository root
P="${1:?usage: setup.sh <project_dir> [brand]}"; BRAND_ID="${2:-buzztorm}"
B="$ROOT/brands/$BRAND_ID"
[ -f "$B/brand-profile.json" ] || { echo "ERROR: unknown brand '$BRAND_ID' (no $B/brand-profile.json). Brands: $(ls "$ROOT/brands" | grep -v '^_' | tr '\n' ' ')"; exit 1; }

mkdir -p "$P"/{work,music,stills,out,ref,brand,delivery}
cp -r "$KIT"/engine/. "$P"/
cp "$KIT"/example/buzztorm_vsl.js "$P"/example_buzztorm_vsl.js   # reference only; the film = vsl.js + story.js
mkdir -p "$P"/audio && cp "$KIT"/audio/*.py "$P"/audio/
cp "$KIT"/tools/*.py "$KIT"/tools/*.sh "$KIT"/tools/*.mjs "$P"/ && rm -f "$P"/setup.sh
cp "$KIT"/sfx/sfx.py "$P"/   # sound effects (catalog + sources live in the library)
cp -r "$KIT"/doc-templates "$P"/doc-templates
mkdir -p "$P"/memes && cp "$KIT"/memes/formats.json "$P"/memes/ && cp -r "$KIT"/memes/templates "$P"/memes/ 2>/dev/null || true && mkdir -p "$P"/doc "$P"/qa
cp -r "$KIT"/ref/. "$P"/ref/
for f in "$KIT"/example/work/*; do [ -e "$P/work/$(basename "$f")" ] || cp "$f" "$P/work/"; done

# —— the brand ——
cp "$B"/brand-profile.json "$P"/brand/
for f in brand-rules.md series-guide.md hooks.md; do [ -f "$B/$f" ] && cp "$B/$f" "$P"/brand/; done
cp -r "$B"/brain "$P"/brand/ 2>/dev/null || true
[ -f "$B/characters/cast.custom.js" ] && cp "$B/characters/cast.custom.js" "$P"/cast.custom.js
[ -f "$B/backgrounds/sets.custom.js" ] && cp "$B/backgrounds/sets.custom.js" "$P"/sets.custom.js
python3 - "$B/brand-profile.json" "$P/brand.js" <<'PY'
import json, sys
b = json.load(open(sys.argv[1]))
out = {"id": b.get("id"), "name": b.get("name"), "colors": b.get("colors", {}), "fonts": b.get("fonts", {}), "signs": {k: v for k, v in (b.get("signs") or {}).items() if v}}
open(sys.argv[2], "w").write("// brand.js — generated by setup.sh from brand-profile.json. Do not edit; edit the brand profile.\nexport const BRAND = " + json.dumps(out, indent=2, ensure_ascii=False) + ";\n")
PY

cd "$P"
# Playwright + Chromium: link an existing install into node_modules, else install it
if [ ! -e node_modules/playwright ]; then
  mkdir -p node_modules
  for d in /opt/npm-tools/node_modules "$(npm root -g 2>/dev/null)" /usr/lib/node_modules /usr/local/lib/node_modules; do
    if [ -d "$d/playwright" ]; then ln -sf "$d/playwright" node_modules/playwright; [ -d "$d/playwright-core" ] && ln -sf "$d/playwright-core" node_modules/playwright-core; break; fi
  done
  [ -e node_modules/playwright ] || { npm i playwright >/dev/null 2>&1 && npx playwright install chromium >/dev/null 2>&1; } || echo "WARN: playwright not available"
fi
python3 -c "import numpy, scipy, soundfile, PIL" 2>/dev/null || pip install --break-system-packages -q numpy scipy soundfile pillow
python3 -c "import pocketsphinx" 2>/dev/null || pip install --break-system-packages -q pocketsphinx || echo "WARN: pocketsphinx missing (needed for align.py)"
command -v ffmpeg >/dev/null || echo "WARN: ffmpeg missing"
echo "project ready: $P  (brand: $BRAND_ID)"
