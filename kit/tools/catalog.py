"""catalog.py <frames_dir> <out_dir> [vsl.js] — scene reference library for consistency.
For every shot() in vsl.js: a 4-frame strip (ref/scenes/NN.jpg) + a CATALOG.md row with time range, the shot's comment,
the sets / characters / props / motion helpers it uses and its line range in vsl.js. Run after a full render."""
import os, re, sys, json
from PIL import Image, ImageDraw
fd, od = sys.argv[1], sys.argv[2]; src_path = sys.argv[3] if len(sys.argv) > 3 else 'vsl.js'
src = open(src_path).read().split('\n'); os.makedirs(od + '/scenes', exist_ok=True)
N = json.load(open('work/lips.json'))['N'] if os.path.exists('work/lips.json') else len(os.listdir(fd)); FPS = 24
starts = [(i, float(m.group(1))) for i, l in enumerate(src) if (m := re.match(r'^shot\(([\d.]+)', l))]
end_src = next(i for i, l in enumerate(src) if l.startswith('// =================== render'))
SETS = r'\b(bg[A-Z]\w*|gymFront|beachSet|twoDoors)\('
CHARS = r'\b(TONY|DEX|CHAR|folk|transformFig)\('
PROPS = r'\b(sign|pill|panel|tag|coin|bill|mug|steam|phone|tablet|chalk|dumbbell|clock|door|adsMachine|umbrella|lounger|beachChair|tripod|recDot|phoneRig|cameraRig|softbox|ringStand|treadBack|treadFront|sweatDrop|arrow|xMark|check)\('
MOTION = r'\b(cam|shake|pop1|poof|stars|seg|ss|eo|ei|eio|back|spring|lerp)\('
rows = []
for k, (li, t0) in enumerate(starts):
    lj = starts[k + 1][0] if k + 1 < len(starts) else end_src
    t1 = starts[k + 1][1] if k + 1 < len(starts) else N / FPS
    body = '\n'.join(src[li:lj]); com = src[li - 1].strip('/ ').strip() if src[li - 1].startswith('//') else ''
    u = lambda rx: sorted(set(re.findall(rx, body)))
    fr = [int((t0 + (t1 - t0) * q) * FPS) for q in (.06, .35, .65, .94)]
    ims = []
    for f in fr:
        p = f'{fd}/f{f:05d}.jpg'
        if not os.path.exists(p): continue
        im = Image.open(p).convert('RGB'); im = im.resize((300, int(im.height * 300 / im.width))); ImageDraw.Draw(im).text((6, 6), f'{f / FPS:.2f}s', fill=(255, 40, 40)); ims.append(im)
    if ims:
        S = Image.new('RGB', (sum(i.width + 6 for i in ims), ims[0].height), 'black'); x = 0
        for im in ims: S.paste(im, (x, 0)); x += im.width + 6
        S.save(f'{od}/scenes/{k:02d}.jpg', quality=80)
    rows.append(f"| {k:02d} | {t0:.2f}–{t1:.2f} | {com} | {', '.join(u(SETS)) or '—'} | {', '.join(u(CHARS)) or '—'} | {', '.join(u(PROPS)) or '—'} | {', '.join(x for x in u(MOTION) if x not in ('seg', 'lerp'))} | L{li + 1}–{lj} | ![](scenes/{k:02d}.jpg) |")
hdr = ['# Scene catalog', '', f'Generated by tools/catalog.py from `{src_path}`. Each strip = 4 frames across the shot (time in red). Reuse a scene by copying its line range; keep sets, outfits and motion the same for consistency.', '',
       '| # | time (s) | beat | sets | characters | props | motion | code | strip |', '|---|---|---|---|---|---|---|---|---|']
open(f'{od}/CATALOG.md', 'w').write('\n'.join(hdr + rows) + '\n'); print(len(rows), 'shots catalogued')
